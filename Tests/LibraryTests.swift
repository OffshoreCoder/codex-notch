import Foundation
@main struct LibraryTests {
    static func main() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: dir) }
        let now = Date()
        func event(_ name: String, _ session: String, _ turn: String, _ offset: Double) -> CompanionEvent {
            CompanionEvent(event: name, sessionID: session, turnID: turn, toolName: nil, toolUseID: nil, timestamp: now.addingTimeInterval(offset))
        }
        var model = CompanionModel()
        let store = LocalStore(directory: dir)
        model.receive(event("UserPromptSubmit", "a", "1", 0))
        model.receive(event("UserPromptSubmit", "b", "2", 1))
        let stop = event("Stop", "a", "1", 2)
        model.receive(stop)
        precondition(model.snapshot(now: now).state == .working)
        let result = model.completion(for: stop)!
        precondition(store.record(result))
        precondition(!store.record(result))
        precondition(LocalStore(directory: dir).data.completions.count == 1)
        store.acknowledge(result.id)
        precondition(!LocalStore(directory: dir).record(result), "ack survives restart and duplicate stop")
        let child = event("Stop", "b", "child", 3)
        model.receive(child)
        precondition(model.completion(for: child) == nil)
        store.remember(model.chatSummaries(now: now))
        store.rename("a", to: "Review\n locally")
        let restored = LocalStore(directory: dir)
        precondition(restored.name(for: "a") == "Review locally")
        precondition(restored.data.chats["b"]?.turnID == "2")
        store.selectImportant("a")
        precondition(store.shouldNotify("a") && !store.shouldNotify("b"))
        precondition(LocalStore(directory: dir).data.importantSessionID == "a")
        store.selectImportant(nil)
        precondition(store.shouldNotify("b"))
        store.beginQuiet(seconds: 30, now: now)
        precondition(store.isQuiet(now: now.addingTimeInterval(29)))
        precondition(!store.shouldNotify("a", now: now))
        let quietResult = CompletedTurn(sessionID: "a", turnID: "quiet", startedAt: now, finishedAt: now)
        _ = store.record(quietResult, now: now)
        precondition(LocalStore(directory: dir).data.deferredCompletionIDs == [quietResult.id])
        precondition(store.quietExpired(now: now.addingTimeInterval(31)))
        precondition(store.endQuiet() == 1 && store.endQuiet() == 0)
        store.beginQuiet(seconds: nil, now: now)
        let viewed = CompletedTurn(sessionID: "b", turnID: "viewed", startedAt: nil, finishedAt: now)
        _ = store.record(viewed, now: now)
        store.acknowledge(viewed.id)
        precondition(store.endQuiet() == 0, "viewed completion must not re-notify")
        store.remindResult("a", after: 10, now: now)
        precondition(store.pollReminders(liveChats: [], now: now.addingTimeInterval(9)).isEmpty)
        precondition(store.pollReminders(liveChats: [], now: now.addingTimeInterval(10)).count == 1)
        precondition(store.pollReminders(liveChats: [], now: now.addingTimeInterval(20)).isEmpty)
        let running = ChatSummary(id: "b", turnID: "2", state: .working, startedAt: now, updatedAt: now)
        store.watchDuration(running, threshold: 10)
        precondition(store.pollReminders(liveChats: [], now: now.addingTimeInterval(11)).isEmpty,
                     "restart cannot prove old turn still running")
        precondition(store.pollReminders(liveChats: [running], now: now.addingTimeInterval(11)).count == 1)
        store.watchDuration(running, threshold: 20)
        let finished = ChatSummary(id: "b", turnID: "2", state: .finished, startedAt: now, updatedAt: now)
        precondition(store.pollReminders(liveChats: [finished], now: now.addingTimeInterval(21)).isEmpty)
        precondition(store.data.reminders.isEmpty)
        store.beginQuiet(seconds: nil, now: now)
        store.remindResult("a", after: 10, now: now)
        precondition(store.pollReminders(liveChats: [], now: now.addingTimeInterval(11)).isEmpty)
        precondition(store.endQuiet() == 1, "due reminder folds into quiet summary once")
        let attrs = try FileManager.default.attributesOfItem(atPath: dir.appendingPathComponent("library.json").path)
        precondition((attrs[.posixPermissions] as? NSNumber)?.intValue == 0o600)
        try Data("broken".utf8).write(to: dir.appendingPathComponent("library.json"))
        let broken = LocalStore(directory: dir)
        precondition(broken.error != nil)
        _ = broken.record(result)
        let preserved = try String(contentsOf: dir.appendingPathComponent("library.json"), encoding: .utf8)
        precondition(preserved == "broken")
        print("Library queue, persistence, duplicates, privacy and corruption checks passed")
    }
}
